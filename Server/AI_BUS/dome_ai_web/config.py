"""
Конфигурация ролей ИИ-агентов купола.

Каждая роль описывается:
- системным промптом (кто он и как себя вести),
- списком разрешённых инструментов (из tool_registry.TOOL_SCHEMAS),
- ключевыми словами для расчёта релевантности — по ним RelevanceScorer решает,
  должен ли агент вступить в разговор, когда кто-то написал новое сообщение.
"""

from dataclasses import dataclass
from typing import List


@dataclass
class AgentConfig:
    key: str                        # короткий идентификатор, напр. "energy"
    name: str                       # отображаемое имя в чате, напр. "Энергетик"
    system_prompt: str
    allowed_tools: List[str]
    topic_keywords: List[str]       # слова/фразы, по которым агент считается релевантным
    always_relevant_on_crisis: bool = False  # реагирует на ЛЮБОЕ кризисное событие
    cooldown_sec: float = 8.0       # минимальная пауза между репликами агента


